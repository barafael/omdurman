#!/usr/bin/env python3
"""Parse RememberGordonManual.md into `section` records (verbatim text) and `cites` edges.

Usage: gen_sections.py <manual.md> <out.surql>

Every heading (`## 5)`, `### 5.2)`, `#### 9.11)`, `### A)`, `### TurnTrack)`) and every bold
numbered paragraph (`**5.21)**`, `**C)**`) opens a section. A section's text runs until the next
section opens. Section ids are the manual's numbers (`section:`5.21``); the turn-sequence parts are
`4.A`, `4.B`, `4.C`; the back-cover notes keep their transcription names.
"""
import json
import re
import sys

HEAD = re.compile(r"^(#{2,4})\s+([0-9]+(?:\.[0-9]+)*|[A-Z]|[A-Za-z]+)\)\s*(.*)$")
BOLD = re.compile(r"^\*\*([0-9]+(?:\.[0-9]+)*|[A-Z])\)\s*(.*?)\*\*\s*(.*)$")
NUM_REF = re.compile(r"(?<![\d.·])(\d{1,2}\.\d{1,3})(?![\d·/])")
BARE_REF = re.compile(r"\b[Ss]ee (\d{1,2})(?= and|\))")          # "see 4 and 6.41"
RANGE_REF = re.compile(r"(\d{1,2}\.\d) to (\d{1,2}\.\d)")       # "see 6.1 to 6.6"
SPECIAL = {"CombatResults": "Explanation of Combat Results", "Disrupted": "Disrupted Units",
           "TurnTrack": "Turn Record Track"}
KIND = {"1": "introduction", "2": "components", "3": "procedure", "4": "turn_sequence",
        "5": "rule", "6": "rule", "7": "rule", "8": "rule", "9": "scenario", "10": "optional_rule",
        "11": "history"}


def parent_of(num: str):
    if num in SPECIAL or num == "credits":
        return None
    if num.startswith("4."):
        return "4"
    if "." not in num:
        return None
    head, tail = num.split(".")
    return head if len(tail) == 1 else f"{head}.{tail[:-1]}"


def sid(num: str) -> str:
    return f"section:`{num}`"


def main(src, out):
    lines = open(src, encoding="utf-8").read().splitlines()
    sections, cur, in_toc = [], None, False
    for line in lines:
        if line.startswith("## Rules of Play"):
            in_toc = True
            continue
        if line.startswith("## Credits"):
            in_toc = False
            cur = {"num": "credits", "title": "Credits", "body": []}
            sections.append(cur)
            continue
        if line.startswith("## Reference: Charts"):
            cur = None
            continue
        m = HEAD.match(line)
        if m:
            in_toc = False
            num, title = m.group(2), m.group(3).strip().rstrip(":")
            if num in ("A", "B"):
                num = f"4.{num}"
            if num in SPECIAL:
                title = SPECIAL[num]
            cur = {"num": num, "title": title, "body": []}
            sections.append(cur)
            continue
        m = BOLD.match(line)
        if m and cur is not None:
            num = m.group(1)
            if num == "C":
                num = "4.C"
            title = m.group(2).strip().rstrip(":")
            cur = {"num": num, "title": title or None, "body": [m.group(3)] if m.group(3) else []}
            sections.append(cur)
            continue
        if in_toc or cur is None:
            continue
        if line.strip() == "---":
            continue
        cur["body"].append(line)

    known = {s["num"] for s in sections}
    out_lines = ["-- GENERATED by tools/gen_sections.py from RememberGordonManual.md -- do not edit.", ""]
    order = 0
    for s in sections:
        order += 1
        text = "\n".join(s["body"]).strip()
        num = s["num"]
        top = num.split(".")[0]
        kind = "reference" if num in SPECIAL else ("credits" if num == "credits" else KIND.get(top, "rule"))
        parent = parent_of(num)
        rec = {
            "num": num,
            "title": s["title"],
            "text": text,
            "kind": kind,
            "ord": order,
            "depth": 0 if parent is None else num.count(".") + (1 if num.startswith("4.") else 0),
        }
        fields = ", ".join(f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in rec.items() if v is not None)
        par = f", parent: {sid(parent)}" if parent and parent in known else ""
        out_lines.append(f"CREATE {sid(num)} CONTENT {{ {fields}{par} }};")
    out_lines.append("")
    out_lines.append("-- Cross-references: `see 6.64`, `(see 5.21)`, `With the exception of 5.21`, ...")
    for s in sections:
        text = "\n".join(s["body"]) + " " + (s["title"] or "")
        refs = []
        found = NUM_REF.findall(text) + BARE_REF.findall(text)
        for a, b in RANGE_REF.findall(text):
            head = a.split(".")[0]
            if head == b.split(".")[0]:
                found += [f"{head}.{i}" for i in range(int(a.split(".")[1]), int(b.split(".")[1]) + 1)]
        for r in found:
            if r in known and r != s["num"] and r not in refs:
                refs.append(r)
        for r in refs:
            out_lines.append(f"RELATE {sid(s['num'])}->cites->{sid(r)};")
    open(out, "w", encoding="utf-8").write("\n".join(out_lines) + "\n")
    print(f"{len(sections)} sections", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
